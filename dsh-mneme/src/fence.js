// 围栏正文的「断链」——把内容里自带的 `<<<` / `>>>` 拆散，使它无法提前闭合我们围出来的围栏。
//
// 为什么单独成模块（#493 的补充，报告者 §③）：断链原先只长在 dream.js 的 fenceListBody
// 里，于是同一件事在三处各有一条命：dream/sleep 的清单（有断链）、蒸馏转录（没有）、
// 画像提取的条目（也没有）。两处一旦分叉，下次出问题就得分别查一遍——#494 与 #501/PR
// #503 的重复劳动就是这么来的。判定逻辑只能有一份实现，这条纪律在本仓已经付过学费
// （scopeStateGate 注释里「过滤点漂移」那条）。
//
// 三个刻意的性质：
// - **只中和标记，不删内容**：被断链的文本仍逐字可读（零宽空格不占位），只是不再是
//   一个能匹配围栏串的连续字符序列。吞掉正文会让「这段记忆说了什么」变成不可复原的。
// - **纯函数、不带 nonce**：重试收到同输入时提示词必须逐字节相同，否则「同输入同错」
//   这条诊断依据就没了（#493 的重试 20 次现场全靠它）。同一份文本调两次结果相同。
// - **不认围栏名字**：三对围栏（转录 / 记忆清单 / 画像条目）都以 `<<<` 开头、`>>>` 收尾，
//   中和这两个前缀/后缀就够了；认名字反而会在新增围栏时漏一处。
/**
 * 断链：`<<<` / `>>>` 中间插一个零宽空格。
 * @param {string} text 任意正文
 * @returns {string} 断链后的正文（未触及的文本逐字节不变）
 */
export function breakFenceMarkers(text) {
  return String(text ?? "").replace(/<<<|>>>/g, (run) => `${run[0]}\u200B${run.slice(1)}`);
}
